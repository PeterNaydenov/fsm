/**
 * Generate `dist/types/main.d.cts` from the ESM declarations in `dist/types/main.d.ts`.
 *
 * The CommonJS bundle uses `module.exports = Fsm`, so CommonJS consumers need
 * `export =` declarations. Every named type is re-exported through a namespace
 * merged with the constructor, e.g. `Fsm.FsmDefinition`.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const
      dir    = new URL ( '../dist/types/', import.meta.url )
    , source = readFileSync ( new URL ( 'main.d.ts', dir ), 'utf8' )
    , names  = [ ...source.matchAll ( /^export type (\w+)/gm ) ].map ( ([, name]) => name )
    , esm    = `import('./main.js', { with: { 'resolution-mode': 'import' } })`
    ;

if ( !names.includes ( 'FsmConstructor' ) )   throw new Error ( 'FsmConstructor type is missing in dist/types/main.d.ts' )

const declarations = `// Generated by scripts/build-cts-types.js. Do not edit.
declare const Fsm: ${esm}.FsmConstructor;
declare namespace Fsm {
${names.map ( name => `    export type ${name} = ${esm}.${name};` ).join ( '\n' )}
}
export = Fsm;
`

writeFileSync ( new URL ( 'main.d.cts', dir ), declarations )
